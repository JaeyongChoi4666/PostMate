-- Add the column once, without deleting categories, states or historical schedules.
SET @postmate_visibility_ddl = IF(
    (SELECT COUNT(*) FROM information_schema.COLUMNS
     WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'TBL_CATEGORY' AND COLUMN_NAME = 'IS_VISIBLE') = 0,
    'ALTER TABLE TBL_CATEGORY ADD COLUMN IS_VISIBLE BOOLEAN NOT NULL DEFAULT TRUE',
    'SELECT 1');
PREPARE postmate_visibility_statement FROM @postmate_visibility_ddl;
EXECUTE postmate_visibility_statement;
DEALLOCATE PREPARE postmate_visibility_statement;

UPDATE TBL_CATEGORY SET IS_VISIBLE = FALSE
WHERE CATE_NAME IN ('체험단', '플레이스 관리', '히든마스터');

INSERT INTO TBL_CATEGORY (CATE_NO, CATE_NAME, IS_VISIBLE)
SELECT 8, '쓰레드', TRUE
WHERE NOT EXISTS (SELECT 1 FROM TBL_CATEGORY WHERE CATE_NO = 8);

